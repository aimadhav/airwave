"""Versioned private voice embeddings; anonymous groups are not verified people."""

from dataclasses import asdict, dataclass
from datetime import datetime
import hashlib
import json
import math
import re
from typing import Any

from recording_viewer.exceptions import VoiceProfileError


def validate_vector(vector: tuple[float, ...]) -> None:
    """Require a nonempty, finite unit vector at the persistence boundary."""
    if (not vector or any(isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v) for v in vector)
            or not math.isclose(sum(v*v for v in vector), 1.0, rel_tol=1e-6, abs_tol=1e-6)):
        raise VoiceProfileError("Voice embeddings must be finite normalized vectors")


@dataclass(frozen=True)
class ProfileContext:
    """Fingerprints bind a profile set to its source, timeline and feature space."""

    source_sha256: str
    audio_sha256: str
    timeline_sha256: str
    encoder_sha256: str
    reference_policy_sha256: str
    backend: str
    sample_rate: int
    bandlimit_rate: int
    preprocessing_version: str

    def __post_init__(self) -> None:
        for name in ("source_sha256", "audio_sha256", "timeline_sha256", "encoder_sha256", "reference_policy_sha256"):
            if not isinstance(getattr(self, name), str) or not re.fullmatch(r"[a-f0-9]{64}", getattr(self, name)):
                raise VoiceProfileError(f"Invalid {name}")
        if (self.backend not in {"nemo_native", "sherpa"}
                or type(self.sample_rate) is not int or self.sample_rate != 16000
                or type(self.bandlimit_rate) is not int or not 0 < self.bandlimit_rate <= self.sample_rate
                or self.preprocessing_version != "titanet_polyphase_bandlimit_v1"):
            raise VoiceProfileError("Invalid profile feature-space specification")

    @property
    def key(self) -> str:
        """Stable namespace; changing source, model or preprocessing creates a new set."""
        return hashlib.sha256(json.dumps(asdict(self), sort_keys=True).encode()).hexdigest()


@dataclass(frozen=True)
class VoiceReference:
    """An embedding from a clean source interval; no additional audio copy is stored."""

    start: float
    end: float
    embedding: tuple[float, ...]

    def __post_init__(self) -> None:
        if (any(isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v) for v in (self.start, self.end))
                or not 0 <= self.start < self.end):
            raise VoiceProfileError("Invalid voice-reference interval")
        validate_vector(self.embedding)


@dataclass(frozen=True)
class SpeakerVoiceProfile:
    """Normalized mean of clean references, never a claimed real-person identity."""

    speaker_id: str
    centroid: tuple[float, ...]
    references: tuple[VoiceReference, ...]
    identity_status: str = "unverified"

    def __post_init__(self) -> None:
        if (not isinstance(self.speaker_id, str) or not re.fullmatch(r"SPEAKER_[0-9]+", self.speaker_id)
                or self.identity_status != "unverified" or not self.references):
            raise VoiceProfileError("Profiles require anonymous speaker IDs and clean references")
        validate_vector(self.centroid)
        if any(len(r.embedding) != len(self.centroid) for r in self.references):
            raise VoiceProfileError("Inconsistent reference embedding dimensions")


@dataclass(frozen=True)
class VoiceProfileSet:
    """Canonical JSON contract for reusable, private, recording-scoped profiles."""

    context: ProfileContext
    created_at: str
    profiles: tuple[SpeakerVoiceProfile, ...]
    warnings: tuple[str, ...] = ()
    schema_version: int = 1

    def __post_init__(self) -> None:
        if type(self.schema_version) is not int or self.schema_version != 1:
            raise VoiceProfileError("Unsupported voice-profile schema")
        try:
            timestamp = datetime.fromisoformat(self.created_at)
        except (TypeError, ValueError) as error:
            raise VoiceProfileError("Invalid profile creation timestamp") from error
        if timestamp.tzinfo is None or not self.profiles or len({p.speaker_id for p in self.profiles}) != len(self.profiles):
            raise VoiceProfileError("Profiles require a zoned timestamp and distinct speakers")
        if len({len(p.centroid) for p in self.profiles}) != 1 or not all(isinstance(w, str) for w in self.warnings):
            raise VoiceProfileError("Invalid profile dimensions or warnings")

    def require_compatible(self, encoder_sha256: str, sample_rate: int, bandlimit_rate: int,
                           preprocessing_version: str) -> None:
        """Do not compare probes generated by another model or preprocessing recipe."""
        actual = (self.context.encoder_sha256, self.context.sample_rate, self.context.bandlimit_rate,
                  self.context.preprocessing_version)
        if actual != (encoder_sha256, sample_rate, bandlimit_rate, preprocessing_version):
            raise VoiceProfileError("Voice-profile model/preprocessing mismatch; regenerate compatible embeddings")

    def to_document(self) -> dict[str, Any]:
        """Serialize only this canonical contract, including individual references."""
        return asdict(self)

    @classmethod
    def from_document(cls, document: dict[str, Any]) -> "VoiceProfileSet":
        """Validate untrusted JSON before exposing any saved embeddings."""
        try:
            values = dict(document)
            values["context"] = ProfileContext(**values["context"])
            values["profiles"] = tuple(SpeakerVoiceProfile(
                **{**p, "centroid": tuple(p["centroid"]), "references": tuple(
                    VoiceReference(**{**r, "embedding": tuple(r["embedding"])}) for r in p["references"])})
                for p in values["profiles"])
            values["warnings"] = tuple(values.get("warnings", ()))
            return cls(**values)
        except (KeyError, TypeError, ValueError) as error:
            raise VoiceProfileError("Malformed voice-profile document") from error
