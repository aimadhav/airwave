"""Narrow provider contracts for offline lab tests and local execution."""

from typing import Protocol
from overlap_lab.models import ExperimentRequest, LabJob, ReferenceAnnotation
from overlap_lab.models.listening import ListeningReview


class ListeningReviewRepository(Protocol):
    """A separate store prevents listening clicks overwriting human transcripts."""

    def reviews(self, recording_id: str) -> dict[str, object]: ...
    def save(self, recording_id: str, source_hash: str, revision: int,
             review: ListeningReview) -> dict[str, object]: ...


class StudyRepository(Protocol):
    def list_recordings(self) -> list[dict[str, object]]: ...
    def study(self, recording_id: str) -> dict[str, object]: ...
    def annotations(self, recording_id: str) -> dict[str, object]: ...
    def save_reference(self, recording_id: str, source_hash: str, revision: int,
                       reference: ReferenceAnnotation) -> dict[str, object]: ...


class ExperimentProcessor(Protocol):
    def capabilities(self) -> list[dict[str, object]]: ...
    def process(self, job_id: str, request: ExperimentRequest) -> dict[str, object]: ...
    def load(self, job_id: str) -> LabJob | None: ...
    def history(self, recording_id: str) -> list[LabJob]: ...
